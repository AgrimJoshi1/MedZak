// Writes src/data/images.generated.ts: every image under public/assets/images with its real size and its
// resized copies in public/assets/images/thumbs (made earlier by the static site's tools/make_thumbs.ps1).
// Run automatically before `dev` and `build`.
import fs from 'node:fs';
import path from 'node:path';
import { imageSize } from 'image-size';

const root = path.resolve('public');
const imagesDir = path.join(root, 'assets', 'images');
const thumbsDir = path.join(imagesDir, 'thumbs');
const out = path.resolve('src', 'data', 'images.generated.ts');

const walk = (dir) =>
  fs.readdirSync(dir, { withFileTypes: true }).flatMap((e) => {
    const p = path.join(dir, e.name);
    return e.isDirectory() ? (e.name === 'thumbs' ? [] : walk(p)) : [p];
  });

const rel = (p) => path.relative(root, p).split(path.sep).join('/');
const thumbs = fs.existsSync(thumbsDir) ? fs.readdirSync(thumbsDir) : [];
const info = {};
const variants = {};

for (const file of walk(imagesDir).filter((f) => /\.(jpe?g|png)$/i.test(f))) {
  const { width, height } = imageSize(fs.readFileSync(file));
  const src = rel(file);
  info[src] = { w: width, h: height };
  const folder = path.basename(path.dirname(file));
  const stem = path.basename(file, path.extname(file));
  const prefix = ['gallery', 'achievements', 'media'].includes(folder) ? `${folder}-` : '';
  const re = new RegExp(`^${(prefix + stem).replace(/[.*+?^${}()|[\]\\]/g, '\\$&')}-(\\d+)\\.(jpg|png)$`);
  const list = thumbs
    .map((t) => ({ t, m: t.match(re) }))
    .filter((x) => x.m)
    .map((x) => ({ src: `assets/images/thumbs/${x.t}`, w: Number(x.m[1]) }))
    .sort((a, b) => a.w - b.w);
  if (list.length) variants[src] = list;
}

const body = `// GENERATED by scripts/gen-images.mjs. Do not edit.
export const IMAGE_SIZES: Record<string, { w: number; h: number }> = ${JSON.stringify(info, null, 1)};

export const IMAGE_VARIANTS: Record<string, { src: string; w: number }[]> = ${JSON.stringify(variants, null, 1)};
`;
fs.mkdirSync(path.dirname(out), { recursive: true });
fs.writeFileSync(out, body);
console.log(`images.generated.ts: ${Object.keys(info).length} images, ${Object.keys(variants).length} with resized copies`);
